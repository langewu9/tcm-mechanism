// Unit-test the R widget hook, without browser/global app access or external requests.
const fs = require('fs'), path = require('path'), vm = require('vm'), assert = require('node:assert/strict');
const code = fs.readFileSync(path.resolve(__dirname,'../../r_viz/interactive.js'),'utf8');
function fixture(type, bipartite = false) {
  const fields = new Map();
  const field = id => { if (!fields.has(id)) fields.set(id,{value:id==='chart-score'?'0':id==='chart-layout'?'circular':'',checked:true,textContent:'',events:{},addEventListener(name,fn){this.events[name]=fn;},append(){},appendChild(){}}); return fields.get(id); };
  const nodes = [{id:'A',name:'A',label:'A',nodeType:'protein',value:1,originalDegree:1},{id:'B',name:'B',label:'B',nodeType:bipartite?'pathway':'protein',value:1,originalDegree:1}];
  if (bipartite) nodes.push({id:'C',name:'C',label:'C',nodeType:'protein',value:0,originalDegree:0});
  const original = JSON.stringify(nodes);
  const opts = {series:[{data:nodes,links:[{source:'A',target:'B',score:0.8}],categories:bipartite?[{name:'pathway'},{name:'protein'}]:[{name:'protein'}]}]};
  const handlers = {};
  const actions=[];
  const chart = {getOption:()=>structuredClone(opts),getWidth:()=>1000,getHeight:()=>740,clear(){actions.push({type:'clearGraphics'});opts.series=[];},setOption(value){opts.series[0]??={};Object.assign(opts.series[0],value.series[0]);},on(name,fn){handlers[name]=fn;},dispatchAction(action){actions.push(action);if(action.type==='restore'&&handlers.brushSelected) handlers.brushSelected({batch:[]});},resize(){}};
  const context = {echarts:{getInstanceByDom:()=>chart},document:{getElementById:field,createElement:()=>({events:{},dataset:{},set id(value){fields.set(value,this);},addEventListener(name,fn){this.events[name]=fn;},append(){}}),createTextNode:t=>t,querySelectorAll:()=>[]},ResizeObserver:class{observe(){}},Set,Map,Number,Array,Object,Math};
  vm.runInNewContext('('+code+')',context)({}, {chartType:type,defaultLayout:bipartite?'layered':'circular',hideIsolatesByDefault:bipartite});
  return {fields,handlers,opts,actions,nodes,original};
}
const graph = fixture('network');
assert.equal(graph.handlers.brushSelected,undefined);
graph.fields.get('chart-search').value='A'; graph.fields.get('chart-find').events.click();
assert.ok(graph.actions.some(action=>action.type==='highlight'));
assert.ok(!graph.actions.some(action=>action.type==='showTip'),'Network search must not synthesize a sticky pointer hover');
assert.ok(graph.fields.get('chart-details').textContent.includes('A'));
graph.fields.get('chart-reset').events.click();
assert.equal(graph.fields.get('chart-search').value,'');
assert.ok(graph.fields.get('chart-details').textContent.includes('视图已重置'));
assert.ok(graph.actions.some(action=>action.type==='clearGraphics'),'Reset must discard persistent graph emphasis/blur state');
graph.fields.get('chart-score').value='0.9'; graph.fields.get('chart-apply').events.click();
assert.equal(graph.opts.series[0].links.length,0);
assert.equal(graph.opts.series[0].data[0].value,0);
graph.fields.get('chart-reset').events.click();
assert.equal(graph.fields.get('chart-score').value,0);
assert.equal(graph.opts.series[0].links.length,1);
const annotation = fixture('network',true);
assert.equal(annotation.fields.get('chart-layout').value,'circular','INPUT-style circular default takes precedence over old two-column metadata');
assert.equal(annotation.opts.series[0].layout,'circular');
assert.equal(annotation.opts.series[0].circular.rotateLabel,true);
assert.equal(annotation.opts.series[0].data.length,2);
assert.ok(annotation.fields.get('chart-status').textContent.includes('已收起 1 个孤立节点'));
assert.ok(annotation.opts.series[0].data.every(n=>n.label.rotate===undefined));
assert.ok(annotation.opts.series[0].links.every(l=>l.lineStyle.curveness===0.32));
assert.equal(annotation.opts.series[0].top,180);
